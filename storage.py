# ─────────────────────────── Бекенди ───────────────────────────

class Database(ABC):
    dialect: str

    @abstractmethod
    async def init(self) -> None: ...

    @abstractmethod
    async def execute(self, sql: str, params: tuple = ()) -> None: ...

    @abstractmethod
    async def insert(self, sql: str, params: tuple = ()) -> int:
        """INSERT у таблицю з колонкою id; повертає id нового рядка."""

    @abstractmethod
    async def run_many(self, statements: list[tuple[str, tuple]]) -> None:
        """Кілька запитів в одній транзакції."""

    @abstractmethod
    async def fetchall(self, sql: str, params: tuple = ()) -> list[dict]:
        """SELECT або запит з RETURNING (зміни фіксуються)."""

    async def fetchone(self, sql: str, params: tuple = ()) -> dict | None:
        rows = await self.fetchall(sql, params)
        return rows[0] if rows else None

    async def close(self) -> None:
        pass

    async def _fill_pool_tokens(self) -> None:
        for row in await self.fetchall("SELECT id FROM pools WHERE invite_token IS NULL"):
            await self.execute("UPDATE pools SET invite_token=? WHERE id=?", (new_pool_token(), row["id"]))


class SQLiteDatabase(Database):
    dialect = "sqlite"

    def __init__(self, path: str):
        self.path = path

    async def _connect(self) -> aiosqlite.Connection:
        conn = await aiosqlite.connect(self.path)
        conn.row_factory = aiosqlite.Row
        await conn.execute("PRAGMA foreign_keys = ON")
        return conn

    async def init(self) -> None:
        os.makedirs(os.path.dirname(os.path.abspath(self.path)), exist_ok=True)
        log.info("Database: SQLite %s", os.path.abspath(self.path))
        conn = await self._connect()
        try:
            await conn.executescript(SQLITE_SCHEMA)
            async with conn.execute("PRAGMA table_info(pools)") as cur:
                columns = {row["name"] for row in await cur.fetchall()}
            if "invite_token" not in columns:  # міграція старих баз
                await conn.execute("ALTER TABLE pools ADD COLUMN invite_token TEXT")
            await conn.execute("CREATE UNIQUE INDEX IF NOT EXISTS idx_pools_token ON pools(invite_token)")
            await conn.commit()
        finally:
            await conn.close()
        await self._fill_pool_tokens()

    async def execute(self, sql: str, params: tuple = ()) -> None:
        conn = await self._connect()
        try:
            await conn.execute(sql, params)
            await conn.commit()
        except sqlite3.IntegrityError as e:
            raise IntegrityError(str(e)) from e
        finally:
            await conn.close()

    async def insert(self, sql: str, params: tuple = ()) -> int:
        conn = await self._connect()
        try:
            cur = await conn.execute(sql, params)
            await conn.commit()
            return cur.lastrowid
        except sqlite3.IntegrityError as e:
            raise IntegrityError(str(e)) from e
        finally:
            await conn.close()

    async def run_many(self, statements: list[tuple[str, tuple]]) -> None:
        conn = await self._connect()
        try:
            for sql, params in statements:
                await conn.execute(sql, params)
            await conn.commit()
        except sqlite3.IntegrityError as e:
            raise IntegrityError(str(e)) from e
        finally:
            await conn.close()

    async def fetchall(self, sql: str, params: tuple = ()) -> list[dict]:
        conn = await self._connect()
        try:
            async with conn.execute(sql, params) as cur:
                rows = [dict(r) for r in await cur.fetchall()]
            await conn.commit()  # для запитів з RETURNING
            return rows
        except sqlite3.IntegrityError as e:
            raise IntegrityError(str(e)) from e
        finally:
            await conn.close()


_QMARK = re.compile(r"'(?:[^']|'')*'|\?")


def qmark_to_dollar(sql: str) -> str:
    """`?` → `$1, $2, ...` (знаки питання всередині рядкових літералів не чіпаються)."""
    counter = 0

    def repl(m: re.Match) -> str:
        nonlocal counter
        if m.group(0) != "?":
            return m.group(0)
        counter += 1
        return f"${counter}"

    return _QMARK.sub(repl, sql)


_DSN = re.compile(r"^(?P<scheme>postgres(?:ql)?)://(?P<user>[^:@/]*)(?::(?P<password>.*))?@(?P<rest>[^@]*)$", re.S)


def normalize_dsn(dsn: str) -> str:
    """Приводить рядок підключення до коректного вигляду:
    • postgres:// → postgresql://;
    • кодує спецсимволи в паролі (/ @ # ? : + % тощо), які інакше ламають розбір адреси.
    Пароль шукається до ОСТАННЬОГО «@», тож «@» у самому паролі теж підтримується."""
    dsn = dsn.strip()
    m = _DSN.match(dsn)
    if not m:
        return dsn
    scheme = "postgresql"
    user, password, rest = m.group("user"), m.group("password"), m.group("rest")
    if password is None:
        return f"{scheme}://{user}@{rest}"
    # Якщо пароль уже закодований (%XX), не кодуємо його вдруге
    raw = unquote(password) if re.search(r"%[0-9A-Fa-f]{2}", password) else password
    return f"{scheme}://{user}:{quote(raw, safe='')}@{rest}"


def mask_dsn(dsn: str) -> str:
    """Безпечний для логів вигляд рядка підключення. Ніколи не кидає винятків і не показує пароль."""
    try:
        parts = urlsplit(normalize_dsn(dsn))
        host = parts.hostname or "?"
        port = f":{parts.port}" if parts.port else ""
        return f"{parts.scheme}://{parts.username or ''}:***@{host}{port}{parts.path}"
    except Exception:  # noqa: BLE001
        return "postgresql://***"


class PostgresDatabase(Database):
    dialect = "postgres"

    def __init__(self, dsn: str):
        self.dsn = normalize_dsn(dsn)
        self.pool = None

    async def init(self) -> None:
        import asyncpg

        self._asyncpg = asyncpg
        log.info("Database: PostgreSQL %s", mask_dsn(self.dsn))
        self.pool = await asyncpg.create_pool(
            self.dsn,
            min_size=1,
            max_size=5,
            # Пулери з'єднань (PgBouncer у Supabase/Neon) у transaction-режимі не підтримують
            # підготовлені запити між транзакціями — вимикаємо кеш, щоб працювало з будь-яким рядком підключення.
            statement_cache_size=0,
            max_inactive_connection_lifetime=60,
            command_timeout=30,
        )
        async with self.pool.acquire() as conn:
            await conn.execute(PG_SCHEMA)
            await conn.execute("ALTER TABLE pools ADD COLUMN IF NOT EXISTS invite_token TEXT")
            await conn.execute("CREATE UNIQUE INDEX IF NOT EXISTS idx_pools_token ON pools(invite_token)")
            # Supabase відкриває таблиці схеми public через свій REST API (Data API). Бот ним не користується,
            # тож вмикаємо Row Level Security без політик: API не бачить даних, а бот (власник таблиць) працює як завжди.
            for table in BOT_TABLES:
                await conn.execute(f"ALTER TABLE {table} ENABLE ROW LEVEL SECURITY")
        await self._fill_pool_tokens()

    async def close(self) -> None:
        if self.pool:
            await self.pool.close()

    async def _run(self, method: str, sql: str, params: tuple):
        asyncpg = self._asyncpg
        query = qmark_to_dollar(sql)
        for attempt in range(2):
            try:
                async with self.pool.acquire() as conn:
                    return await getattr(conn, method)(query, *params)
            except (asyncpg.UniqueViolationError, asyncpg.ForeignKeyViolationError) as e:
                raise IntegrityError(str(e)) from e
            except (asyncpg.ConnectionDoesNotExistError, asyncpg.InterfaceError,
                    asyncpg.CannotConnectNowError, ConnectionError, OSError) as e:
                # Безкоштовні бази «засинають» і рвуть неактивні з'єднання — одна повторна спроба
                if attempt == 1:
                    raise
                log.warning("DB connection problem (%s), retrying", e.__class__.__name__)

    async def execute(self, sql: str, params: tuple = ()) -> None:
        await self._run("execute", sql, params)

    async def insert(self, sql: str, params: tuple = ()) -> int:
        return await self._run("fetchval", sql + " RETURNING id", params)

    async def fetchall(self, sql: str, params: tuple = ()) -> list[dict]:
        return [dict(r) for r in await self._run("fetch", sql, params)]

    async def run_many(self, statements: list[tuple[str, tuple]]) -> None:
        asyncpg = self._asyncpg
        try:
            async with self.pool.acquire() as conn:
                async with conn.transaction():
                    for sql, params in statements:
                        await conn.execute(qmark_to_dollar(sql), *params)
        except (asyncpg.UniqueViolationError, asyncpg.ForeignKeyViolationError) as e:
            raise IntegrityError(str(e)) from e


def create_database() -> Database:
    url = os.getenv("DATABASE_URL", "").strip()
    if url:
        return PostgresDatabase(url)  # normalize_dsn виправляє схему й кодує пароль
    return SQLiteDatabase(os.getenv("DB_PATH", "bot.db"))


# ─────────────────────────── Блокування лідера ───────────────────────────

def _utc(dt: datetime) -> str:
    return dt.astimezone(timezone.utc).strftime("%Y-%m-%d %H:%M:%S.%f")


class LeaderLock:
    """Оренда (lease) у таблиці leader_lock: лідер щоразу продовжує її до expires_at.
    Якщо лідер зник і не продовжив оренду — після її закінчення лідером може стати інша копія."""

    def __init__(self, db: Database, ttl: int = 60, name: str = "main"):
        self.db = db
        self.ttl = ttl
        self.name = name
        self.holder = f"{socket.gethostname()}:{os.getpid()}:{uuid.uuid4().hex[:8]}"

    async def try_acquire(self) -> bool:
        """Захопити або продовжити оренду. True — ця копія є лідером."""
        if self.db.dialect == "sqlite" and sqlite3.sqlite_version_info < (3, 35, 0):
            return True  # стара SQLite без RETURNING: локальний файл і так означає одну копію
        now = datetime.now(timezone.utc)
        row = await self.db.fetchone(
            """INSERT INTO leader_lock(name, holder, expires_at) VALUES(?, ?, ?)
               ON CONFLICT(name) DO UPDATE SET holder=excluded.holder, expires_at=excluded.expires_at
               WHERE leader_lock.expires_at < ? OR leader_lock.holder = excluded.holder
               RETURNING holder""",
            (self.name, self.holder, _utc(now + timedelta(seconds=self.ttl)), _utc(now)),
        )
        return bool(row and row["holder"] == self.holder)

    async def release(self) -> None:
        await self.db.execute("DELETE FROM leader_lock WHERE name=? AND holder=?", (self.name, self.holder))

    async def current_holder(self) -> dict | None:
        return await self.db.fetchone("SELECT holder, expires_at FROM leader_lock WHERE name=?", (self.name,))